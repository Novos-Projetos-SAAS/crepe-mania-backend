export async function apply(trx) {
  const categories = await trx('categorias_produtos').select('id', 'slug');
  const bySlug = new Map(categories.map(({ id, slug }) => [slug, id]));
  for (const item of PRODUTOS) {
    const categoria_id = bySlug.get(item.categoria);
    if (!categoria_id) throw new Error(`Categoria nao encontrada: ${item.categoria}. Execute seeds em ordem.`);
    const exists = await trx('produtos').where({ categoria_id, nome: item.nome }).first();
    if (!exists) await trx('produtos').insert({ categoria_id, nome: item.nome, tipo: item.tipo,
      preco_base: null, ativo: false, disponivel_hoje: false, ordem_exibicao: 0 });
  }
}
